function validateOptions(options) {
  assertFileExists(options.datasetPath, "ML dataset");

  if (options.requireSummary) {
    assertFileExists(options.summaryPath, "ML dataset summary");
  }
}

function main(argv = process.argv.slice(2)) {
  try {
    const options = parseArguments(argv);

    if (options.help) {
      printHelp();
      return;
    }

    validateOptions(options);

    const datasetEntries = loadJsonlDataset(options.datasetPath);

    const validation = validateDatasetRows(datasetEntries);

    const featureNames = determineFeatureNames(datasetEntries);

    const inspection = buildDatasetInspection({
      datasetPath: options.datasetPath,
      datasetEntries,
      featureNames,
    });

    let summaryMismatches = [];

    if (options.requireSummary) {
      const summary = readJson(options.summaryPath, "ML dataset summary");

      summaryMismatches = compareInspectionWithSummary({
        inspection,
        summary,
      });
    }

    printInspection({
      inspection,
      validation,
      summaryMismatches,
    });

    if (validation.errors.length > 0 || summaryMismatches.length > 0) {
      if (validation.errors.length > 0) {
        console.error("");
        console.error("Dataset validation errors:");

        for (const error of validation.errors) {
          console.error(`- ${error}`);
        }
      }

      process.exitCode = 1;
      return;
    }

    console.log("");
    console.log("Dataset inspection passed.");
  } catch (error) {
    console.error("");
    console.error(`Baseline dataset inspection failed: ${error.message}`);

    process.exitCode = 1;
  }
}

if (require.main === module) {
  main();
}

