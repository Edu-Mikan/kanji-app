"use strict";

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const DEFAULT_DATASET_PATH = path.resolve(
  process.cwd(),
  "ml_datasets",
  "reference_candidate_binary_dataset.jsonl",
);

const DEFAULT_SUMMARY_PATH = path.resolve(
  process.cwd(),
  "ml_datasets",
  "reference_candidate_binary_dataset_summary.json",
);

const VALID_CLASSIFICATIONS = new Set([
  "truePositive",
  "trueNegative",
  "falsePositive",
  "falseNegative",
]);

const POSITIVE_DESCRIPTOR_CLASSIFICATIONS = new Set([
  "truePositive",
  "falsePositive",
]);

const NEGATIVE_DESCRIPTOR_CLASSIFICATIONS = new Set([
  "trueNegative",
  "falseNegative",
]);

const POTENTIAL_LEAKAGE_PATTERNS = [
  /label/i,
  /target/i,
  /correct/i,
  /classification/i,
  /prediction/i,
  /predicted/i,
  /accepted/i,
  /rejected/i,
  /result/i,
  /truepositive/i,
  /truenegative/i,
  /falsepositive/i,
  /falsenegative/i,
];

function parseArguments(argv) {
  const options = {
    datasetPath: DEFAULT_DATASET_PATH,
    summaryPath: DEFAULT_SUMMARY_PATH,
    requireSummary: true,
    help: false,
  };

  for (let index = 0; index < argv.length; index++) {
    const argument = argv[index];

    if (argument === "--dataset") {
      options.datasetPath = path.resolve(
        process.cwd(),
        requireArgumentValue(argv, index, argument),
      );

      index++;
      continue;
    }

    if (argument === "--summary") {
      options.summaryPath = path.resolve(
        process.cwd(),
        requireArgumentValue(argv, index, argument),
      );

      index++;
      continue;
    }

    if (argument === "--no-summary") {
      options.requireSummary = false;
      continue;
    }

    if (argument === "--help" || argument === "-h") {
      options.help = true;
      continue;
    }

    throw new Error(`Unknown argument: ${argument}`);
  }

  return options;
}

function requireArgumentValue(argv, index, argumentName) {
  const value = argv[index + 1];

  if (!value || value.startsWith("--")) {
    throw new Error(`${argumentName} requires a value`);
  }

  return value;
}

